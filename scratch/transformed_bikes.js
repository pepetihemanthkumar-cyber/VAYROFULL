function createBike({
  brand,
  model,
  category,
  bikeClass,
  fuelType = 'Petrol',
  enginePower = '350cc',
  transmission = 'Manual',
  dailyRate,
  status = 'AVAILABLE',
}) {
  const id = `${brand}-${model}`.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
  const isScooter = category === 'SCOOTER' || category === 'ELECTRIC' || transmission === 'Automatic'
  const isEv = fuelType === 'Electric'

  const features = isEv
    ? ['TFT Touchscreen', 'Regenerative Braking', 'Reverse Parking Mode', 'Fast Charging Support', 'Smart App Connectivity', 'Anti-Theft Geofencing']
    : isScooter
    ? ['Combined Braking System (CBS)', 'LED Headlamp', 'Underseat Storage', 'USB Mobile Charger', 'Telescopic Suspension', 'Side-Stand Engine Cutoff']
    : ['Dual-Channel ABS', 'Slipper & Assist Clutch', 'Digital LCD Console', 'LED Projector Lights', 'Bluetooth Navigation Turn-by-Turn', 'Hazard Light Switch']

  const description = `DriveEase certified fleet ${brand} ${model} engineered for exhilarating performance, precision handling, and unmatched road reliability across city and highway journeys.`

  const localImg = bikeImageMap[id]

  return {
    id,
    name: `${brand} ${model}`,
    brand,
    model,
    year: 2024,
    vehicleType: 'bike',
    category,
    class: bikeClass,
    type: category,
    status,
    seats: 2,
    transmission,
    fuelType,
    engine: isEv ? undefined : enginePower.split('·')[0]?.trim(),
    enginePower: enginePower,
    helmetsIncluded: '1 DOT-Certified Helmet Included',
    airConditioning: false,
    description,
    features,
    dailyRate,
    pricing: createBikePricing(dailyRate),
    image: localImg,
    imagePosition: 'center',
    images: {
      primary: localImg,
      gallery: [localImg],
    },
    imageVerified: true,
    imageSource: 'local-verified',
  }
}

const bikes = bikeCatalogue.flatMap(([brand, models]) =>
  models.map(([model, category, bikeClass, fuelType, enginePower, transmission, dailyRate, status = 'AVAILABLE']) => {
    return createBike({
      brand,
      model,
      category,
      bikeClass,
      fuelType,
      enginePower,
      transmission,
      dailyRate,
      status,
    })
  }),
)

function getBikeById(id) {
  return bikes.find((bike) => bike.id === id)
}

function getBikes() {
  return bikes
}

